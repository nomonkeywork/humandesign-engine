// Regenerates src/data/bodygraph-svg.js from hdkit's blank bodygraph SVG
// (https://github.com/jdempcy/hdkit, MIT — sample-apps/hdkit_sample_app/
// app/assets/images/bodygraph-blank.svg). Usage:
//   node scripts/extract-bodygraph-svg.mjs <path/to/bodygraph-blank.svg>
import fs from 'node:fs';

const src = process.argv[2];
if (!src) throw new Error('usage: extract-bodygraph-svg.mjs <bodygraph-blank.svg>');
const svg = fs.readFileSync(src, 'utf8');

const attr = (tag, name) => (tag.match(new RegExp(`\\s${name}="([^"]*)"`)) || [])[1];
const viewBox = svg.match(/viewBox="([^"]+)"/)[1];

// ── Channel halves: every <path|polygon|polyline id="Gate{n}"> inside <g id="Channels">
const channelsBlock = svg.slice(svg.indexOf('<g id="Channels"'), svg.indexOf('<g id="Centers"'));
const gatePaths = [];
for (const m of channelsBlock.matchAll(/<(path|polygon|polyline)\b[^>]*>/g)) {
  const tag = m[0];
  const id = attr(tag, 'id');
  if (!id) continue;
  const num = id.match(/^Gate(\d+)$/);
  const shape =
    m[1] === 'path'
      ? { d: attr(tag, 'd') }
      : { points: attr(tag, 'points') };
  if (num) gatePaths.push({ gate: Number(num[1]), ...shape });
  else gatePaths.push({ extra: id, ...shape }); // GateSpan / GateConnect34 / GateConnect10
}

// ── Centers: <g id="Head"> … each holds one path
const centersBlock = svg.slice(svg.indexOf('<g id="Centers"'), svg.indexOf('<g id="Gates"'));
const centers = [];
for (const m of centersBlock.matchAll(/<g id="([A-Za-z]+)">\s*<path[^>]*\sd="([^"]+)"/g)) {
  centers.push({ id: m[1], d: m[2] });
}

// ── Gate number labels
const texts = [];
for (const m of svg.matchAll(/<text\b[^>]*id="GateText(\d+)"[^>]*transform="translate\(([-\d.]+)[ ,]([-\d.]+)\)"[^>]*>(\d+)<\/text>/g)) {
  texts.push({ gate: Number(m[1]), x: Number(m[2]), y: Number(m[3]) });
}

const out = `// GENERATED by scripts/extract-bodygraph-svg.mjs — do not edit by hand.
//
// Geometry (viewBox, channel halves, centers, gate labels) taken from
// hdkit's bodygraph-blank.svg, https://github.com/jdempcy/hdkit
// MIT License, Copyright (c) 2016-2023 Jonah Dempcy — see THIRD_PARTY_LICENSES/hdkit.txt.

export const BODYGRAPH_VIEWBOX = ${JSON.stringify(viewBox)};

/** One drawable half-channel per gate (a channel = its two gate halves meeting mid-way): { gate, d | points }. */
export const GATE_SHAPES = ${JSON.stringify(gatePaths.filter((p) => p.gate), null, 0)};
/** Connector pieces of the 10–57 / 34–20 / 34–57 diagonal that belong to a specific gate: { extra, d | points }. */
export const EXTRA_SHAPES = ${JSON.stringify(gatePaths.filter((p) => p.extra), null, 0)};
/** The nine centers: { id, d } with hdkit's ids (Head, Ajna, Throat, G, Ego, Spleen, SolarPlexus, Sacral, Root). */
export const CENTER_SHAPES = ${JSON.stringify(centers, null, 0)};
/** Where each gate's number is printed: { gate, x, y }. */
export const GATE_LABELS = ${JSON.stringify(texts, null, 0)};
`;
fs.writeFileSync(new URL('../src/data/bodygraph-svg.js', import.meta.url), out);
console.log(`gates:${gatePaths.filter((p) => p.gate).length} extras:${gatePaths.filter((p) => p.extra).length} centers:${centers.length} labels:${texts.length}`);
